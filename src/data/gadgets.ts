export const byTag = (tag: NonNullable<Gadget["tags"]>[number]) =>
  gadgets.filter((g) => g.tags?.includes(tag));

export const byCategory = (...cats: GadgetCategory[]) =>
  gadgets.filter((g) => cats.includes(g.category));

export const byBrand = (brand: string) => gadgets.filter((g) => g.brand === brand);

export const newArrivals = gadgets.filter((g) => g.isNew);

